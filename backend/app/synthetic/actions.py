"""
The Action Catalog — the single, authoritative list of every action a user can
perform in the Logistics Control Tower, module by module, sub-module by
sub-module, tab by tab.

This file answers three questions in one place:

  1. WHAT can a human do here?      → the catalog rows
  2. CAN ATLAS do it autonomously?  → `ai_capable` + `autonomy`
  3. WHEN must a human decide?      → `autonomy: human`/`dual` + `approval_trigger`
                                      + the severity / confidence / value gates

Everything downstream reads from here:

  * `ACTION_THRESHOLDS`  — the per-action autonomy policy the agent engine
    evaluates before it self-executes anything (derived, not hand-maintained).
  * The Governance tab   — renders the catalog verbatim, so what the operator
    reads is literally the policy the engine enforces.
  * The reasoning tracer — uses `consults` to decide which specialist
    capabilities are pulled into the cross-agent negotiation for an action.

AUTONOMY CLASSES
    observe   Read, filter, drill, navigate. ATLAS does these continuously and
              silently — there is nothing to approve.
    auto      State-changing, but routine, bounded and reversible. Self-executes
              while severity ≤ ceiling, confidence ≥ floor and value ≤ ceiling.
              Any breach of a gate escalates it to a human.
    human     Always escalated. High stakes, irreversible, contractual,
              reputational or regulatory — judgement the business owns.
    dual      Escalated AND requires a second approver above the dual-control
              value line.

REVERSIBILITY / BLAST RADIUS are the two levers that decide which class an
action lands in: an action that is irreversible OR network-wide is never `auto`.
"""

