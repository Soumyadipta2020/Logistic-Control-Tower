def _a(key, label, *, module, tab, section, category, permission=None, agent=None,
       autonomy="observe", threshold_key=None, severity_ceiling="medium",
       confidence_floor=70, value_ceiling_gbp=0, commits_spend=False,
       reversibility="reversible", blast_radius="record", sla_minutes=None,
       approval_trigger=None, why_human=None, consults=(), executes=None, description=""):
    """One catalog row. Defaults describe a harmless read; every state change
    overrides them explicitly so nothing becomes autonomous by accident.

    `commits_spend` decides whether the GLOBAL auto-approve guardrail bites. It
    is set only where money actually leaves the business — a purchase order, an
    expedite premium. Relocating stock the business already owns has a value, but
    it is not spend, so it is governed by its own ceiling alone. Conflating the
    two would either cap transfers absurdly low or let purchasing run too free.
    """
