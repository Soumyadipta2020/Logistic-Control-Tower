# ── Derived: the policy the agent engine actually enforces ────────────────────
# Kept in the exact shape the engine has always consumed, so the catalog above
# is the only place a threshold is ever edited.
def _thresholds() -> dict:
    out = {}
    for a in ACTION_CATALOG:
        tk = a.get("threshold_key")
        if not tk:
            continue
        out[tk] = {
            "label": a["label"],
            # The engine understands auto vs. escalate; dual-control is a stricter
            # human class, so it maps to "human" plus the dual_control flag.
            "autonomy": "auto" if a["autonomy"] == "auto" else "human",
            "value_ceiling_gbp": a["value_ceiling_gbp"],
            "commits_spend": a["commits_spend"],
            "severity_ceiling": a["severity_ceiling"],
            "confidence_floor": a["confidence_floor"],
            "dual_control": a["autonomy"] == "dual",
            "module": a["module"], "module_label": a["module_label"],
            "tab": a["tab"], "section": a["section"],
            "permission": a["permission"], "agent": a["agent"],
            "category": a["category"], "reversibility": a["reversibility"],
            "blast_radius": a["blast_radius"], "sla_minutes": a["sla_minutes"],
            "approval_trigger": a["approval_trigger"], "why_human": a["why_human"],
            "consults": a["consults"], "action_key": a["key"],
        }
    return out


ACTION_THRESHOLDS = _thresholds()


def catalog_summary() -> dict:
    """Counts the Governance tab leads with, so the header states the policy
    posture in one line without the UI re-deriving it."""
    by_class: dict[str, int] = {}
    by_module: dict[str, dict] = {}
    for a in ACTION_CATALOG:
        by_class[a["autonomy"]] = by_class.get(a["autonomy"], 0) + 1
        m = by_module.setdefault(a["module"], {
            "module": a["module"], "module_label": a["module_label"],
            "total": 0, "observe": 0, "auto": 0, "human": 0, "dual": 0})
        m["total"] += 1
        m[a["autonomy"]] += 1
    state_changing = [a for a in ACTION_CATALOG if a["category"] in ("execute", "govern")]
    autonomous = [a for a in state_changing if a["autonomy"] == "auto"]
    return {
        "total_actions": len(ACTION_CATALOG),
        "state_changing": len(state_changing),
        "autonomous": len(autonomous),
        "human_gated": len([a for a in state_changing if a["autonomy"] in ("human", "dual")]),
        "dual_control": by_class.get("dual", 0),
        "autonomy_pct": round(len(autonomous) / len(state_changing) * 100) if state_changing else 0,
        "by_class": by_class,
        "by_module": sorted(by_module.values(), key=lambda m: -m["total"]),
    }
